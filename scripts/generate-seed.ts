/**
 * Writes supabase/seed.sql from the demo dataset (identical to the mockup generator).
 * Run: npm run seed:sql
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { DEMO_REPORTS } from '../src/lib/demo';

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (a: string[]) => `array[${a.map(q).join(', ')}]::text[]`;

const out: string[] = [
  '-- Demo seed: generated by scripts/generate-seed.ts (npm run seed:sql). Do not edit by hand.',
  '-- Two demo clients from the mockup, with stable ids.',
  'begin;',
];

for (const r of Object.values(DEMO_REPORTS)) {
  const c = r.client;
  out.push(
    `insert into public.clients (id, name, category, address, locality, phone, website, services, brand_color, logo_path, client_since, hours) values (` +
      [q(c.id), q(c.name), q(c.category), q(c.address), q(c.locality), q(c.phone), q(c.website), arr(c.services), q(c.brand_color), 'null', q(c.client_since), j(c.hours)].join(', ') +
      `)\n  on conflict (id) do update set name = excluded.name, category = excluded.category, address = excluded.address, locality = excluded.locality, phone = excluded.phone, website = excluded.website, services = excluded.services, brand_color = excluded.brand_color, client_since = excluded.client_since, hours = excluded.hours;`,
  );
  for (const m of r.months) {
    out.push(
      `insert into public.months (client_id, period, published, nap, entity, schema_cov, knowledge, mentions, nap_fields, entity_parts, engines, work, sources, forum, note) values (` +
        [q(c.id), q(m.period), q(m.published), q(m.nap), q(m.entity), q(m.schema_cov), q(m.knowledge), q(m.mentions), j(m.nap_fields), j(m.entity_parts), j(m.engines), j(m.work), j(m.sources), j(m.forum), q(m.note)].join(', ') +
        `)\n  on conflict (client_id, period) do update set published = excluded.published, nap = excluded.nap, entity = excluded.entity, schema_cov = excluded.schema_cov, knowledge = excluded.knowledge, mentions = excluded.mentions, nap_fields = excluded.nap_fields, entity_parts = excluded.entity_parts, engines = excluded.engines, work = excluded.work, sources = excluded.sources, forum = excluded.forum, note = excluded.note, updated_at = now();`,
    );
  }
}

out.push('commit;', '');

const path = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url));
writeFileSync(path, out.join('\n\n'));
console.log(`Wrote ${path}`);
