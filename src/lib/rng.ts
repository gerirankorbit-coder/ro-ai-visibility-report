/** Seeded LCG, identical to the mockup's generator so demo values match exactly. */
export function rng(seed: string): () => number {
  let s = 0;
  for (const ch of String(seed)) s = (s * 31 + ch.charCodeAt(0)) >>> 0;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296;
  };
}
